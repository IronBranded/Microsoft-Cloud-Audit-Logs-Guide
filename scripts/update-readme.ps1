#Requires -Version 7.4
<#
.SYNOPSIS
    Regenerates the evidence-source list in README.md from the catalog.

.DESCRIPTION
    Rewrites only the part of README.md between the BEGIN and END evidence-sources markers. For every
    evidence source shown on the site it lists the product, evidence type, availability, and two
    Microsoft Learn links: the product's "What is" overview and the evidence source's own documentation.
    All values come from data/evidence-catalog.json, data/products.json, and data/sources.json, so the
    README cannot drift from the posters and the site.

.EXAMPLE
    pwsh ./scripts/update-readme.ps1
#>
[CmdletBinding()]
param(
    [string]$RepoRoot = (Split-Path -Parent $PSScriptRoot)
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

function Read-Json([string]$name) {
    Get-Content -LiteralPath (Join-Path $RepoRoot "data/$name") -Raw | ConvertFrom-Json -Depth 64
}
$catalog = Read-Json 'evidence-catalog.json'
$products = Read-Json 'products.json'
$sources = Read-Json 'sources.json'
$copy = Read-Json 'presentation.json'

$sourceById = @{}; foreach ($s in $sources.sources) { $sourceById[$s.id] = $s }
$productById = @{}; foreach ($p in $products.products) { $productById[$p.id] = $p }
$entryById = @{}; foreach ($e in $catalog.entries) { $entryById[$e.id] = $e }
$priorityOrder = @{ Core = 0; Extended = 1; Specialized = 2 }

# Verb-noun name on purpose: 'md' is a built-in alias for mkdir, and aliases win over functions.
function ConvertTo-MarkdownCell([string]$text) { $text -replace '\|', '\|' }
function Get-LearnLink([string]$sourceId) {
    if (-not $sourceById.ContainsKey($sourceId)) { throw "Unknown source id '$sourceId'." }
    $s = $sourceById[$sourceId]
    if ($s.url -notmatch '^https://learn\.microsoft\.com/') { throw "Source $sourceId is not a Microsoft Learn URL." }
    "[$(ConvertTo-MarkdownCell $s.title)]($($s.url))"
}

$entries = @($catalog.entries | Where-Object { $_.publication.site })
$lastVerified = ($entries.verification.last_verified | ForEach-Object { [string]$_ } | Sort-Object -Descending | Select-Object -First 1)

$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine("$($entries.Count) evidence sources from $(@($products.products).Count) Microsoft products, grouped by evidence plane. Each row links to the product's Microsoft Learn overview (**What is**) and to the Microsoft Learn page that documents the evidence itself (**Evidence**). Catalog last checked against Microsoft Learn on $lastVerified.")
[void]$sb.AppendLine()
[void]$sb.AppendLine('**Availability** says whether the evidence exists without preparation. Anything other than "Automatic" means something had to be configured, licensed, deployed, or requested before the activity happened.')
[void]$sb.AppendLine()

$notCovered = [System.Collections.Generic.List[string]]::new()
foreach ($plane in $copy.planes) {
    $items = @($entries | Where-Object { $_.evidence_plane -eq $plane.name } |
        Sort-Object @{ Expression = { $priorityOrder[$_.priority] } }, @{ Expression = { $_.evidence_source } })
    if ($items.Count -eq 0) { $notCovered.Add($plane.name); continue }

    [void]$sb.AppendLine(('### {0:D2}. {1}' -f [int]$plane.number, $plane.name))
    [void]$sb.AppendLine()
    [void]$sb.AppendLine('| Evidence source | Product | Evidence type | Availability | Microsoft Learn |')
    [void]$sb.AppendLine('|---|---|---|---|---|')
    foreach ($e in $items) {
        $p = $productById[$e.product_id]
        $name = ConvertTo-MarkdownCell $e.evidence_source
        if ($e.replaced_by -and $entryById.ContainsKey($e.replaced_by)) {
            $name += " (retiring; use $(ConvertTo-MarkdownCell $entryById[$e.replaced_by].evidence_source))"
        }
        $learn = "What is: $(Get-LearnLink $p.what_is_source_id)<br>Evidence: $(Get-LearnLink $e.evidence_doc_source_id)"
        [void]$sb.AppendLine("| $name | $(ConvertTo-MarkdownCell $p.name) | $(ConvertTo-MarkdownCell $e.evidence_type) | $(ConvertTo-MarkdownCell $e.availability) | $learn |")
    }
    [void]$sb.AppendLine()
}
if ($notCovered.Count) {
    [void]$sb.AppendLine("**Not yet covered:** $($notCovered -join ', '). These planes are planned; no entry is published until it is checked against Microsoft Learn.")
}

$readmePath = Join-Path $RepoRoot 'README.md'
$readme = Get-Content -LiteralPath $readmePath -Raw
$begin = '<!-- BEGIN evidence-sources: generated by scripts/update-readme.ps1 from data/. Do not edit by hand. -->'
$end = '<!-- END evidence-sources -->'
$pattern = '(?s)' + [regex]::Escape($begin) + '.*?' + [regex]::Escape($end)
if ($readme -notmatch $pattern) { throw "README.md has no evidence-sources markers." }
$generated = $begin + "`n" + ($sb.ToString() -replace "`r`n", "`n").TrimEnd() + "`n" + $end
$updated = [regex]::Replace($readme, $pattern, { param($m) $generated })
[System.IO.File]::WriteAllText($readmePath, ($updated -replace "`r`n", "`n"), [System.Text.UTF8Encoding]::new($false))
Write-Host "README.md evidence list updated: $($entries.Count) evidence sources."
